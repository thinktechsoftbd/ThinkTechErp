-- Lookup lists (public schema, shared by every module), organization object IDs, subscription
-- modules and organization subscriptions, with their menus and permissions.
--
-- Timestamps: the database time zone is Europe/Berlin, so DEFAULT CURRENT_TIMESTAMP on a
-- "timestamp" column would store Berlin local time. The security schema (and the API) store
-- UTC, so these defaults use now() AT TIME ZONE 'utc'.
-- The script is idempotent: running it again changes nothing.

BEGIN;

-- =====================================================================
-- Lookup tables: named lists of values, e.g. "Currency" -> BDT, USD
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.lookup_table
(
    lookup_table_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lookup_table_name VARCHAR(150) NOT NULL,
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,

    created_at        TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by        INT NULL,
    updated_at        TIMESTAMP(3) NULL,
    updated_by        INT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_lookup_table_name
    ON public.lookup_table (lower(lookup_table_name));

CREATE TABLE IF NOT EXISTS public.lookup_data
(
    lookup_data_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lookup_table_id   BIGINT NOT NULL,
    lookup_data_name  VARCHAR(150) NOT NULL,
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,

    created_at        TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by        INT NULL,
    updated_at        TIMESTAMP(3) NULL,
    updated_by        INT NULL,

    CONSTRAINT fk_lookup_data_lookup_table
        FOREIGN KEY (lookup_table_id)
        REFERENCES public.lookup_table (lookup_table_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_lookup_data_lookup_table_id
    ON public.lookup_data (lookup_table_id);

-- A value appears once per lookup table, regardless of case.
CREATE UNIQUE INDEX IF NOT EXISTS ux_lookup_data_name
    ON public.lookup_data (lookup_table_id, lower(lookup_data_name));

-- Subscriptions are billed in a currency from this list.
INSERT INTO public.lookup_table (lookup_table_name)
VALUES ('Currency')
ON CONFLICT DO NOTHING;

INSERT INTO public.lookup_data (lookup_table_id, lookup_data_name)
SELECT t.lookup_table_id, v.name
FROM public.lookup_table t
CROSS JOIN (VALUES ('BDT'), ('USD')) AS v(name)
WHERE lower(t.lookup_table_name) = 'currency'
ON CONFLICT DO NOTHING;

-- =====================================================================
-- Organization object ID
-- =====================================================================

-- Existing rows each get their own UUID when the column is added.
ALTER TABLE security.organization
    ADD COLUMN IF NOT EXISTS object_id uuid NOT NULL DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS ux_organization_object_id
    ON security.organization (object_id);

-- =====================================================================
-- Subscription modules and subscriptions
-- =====================================================================

CREATE TABLE IF NOT EXISTS security.subscription_module
(
    subscription_module_id INT GENERATED ALWAYS AS IDENTITY,
    object_id              uuid NOT NULL DEFAULT gen_random_uuid(),
    module_name            text NOT NULL,
    is_active              bool NOT NULL DEFAULT true,
    remarks                text NULL,

    created_at             timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by             int4 NULL,
    updated_at             timestamp(3) NULL,
    updated_by             int4 NULL,

    CONSTRAINT pk_subscription_module
        PRIMARY KEY (subscription_module_id),

    CONSTRAINT ck_subscription_module_name
        CHECK (length(btrim(module_name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_module_object_id
    ON security.subscription_module (object_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_module_name
    ON security.subscription_module (lower(module_name));

CREATE TABLE IF NOT EXISTS security.subscription
(
    subscription_id BIGINT GENERATED ALWAYS AS IDENTITY,

    organization_id INT NOT NULL,
    subscription_module_id INT NOT NULL,

    subscription_type VARCHAR(20) NOT NULL,
    -- Free Trial, Premium

    billing_period_type VARCHAR(10) NOT NULL,
    -- Monthly, Yearly

    billing_period_count INT NOT NULL DEFAULT 1,

    subscription_start_date DATE NOT NULL,
    subscription_end_date DATE NOT NULL,

    currency_lookup_data_id BIGINT NOT NULL,
    local_exchange_rate NUMERIC(18, 6) NOT NULL DEFAULT 1,

    subtotal_amount NUMERIC(18, 2) NOT NULL DEFAULT 0,
    discount_percentage NUMERIC(5, 2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(18, 2) NOT NULL DEFAULT 0,
    vat_amount NUMERIC(18, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(18, 2) NOT NULL DEFAULT 0,

    status VARCHAR(20) NOT NULL DEFAULT 'Active',

    created_at TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by INT NULL,
    updated_at TIMESTAMP(3) NULL,
    updated_by INT NULL,

    CONSTRAINT pk_subscription
        PRIMARY KEY (subscription_id),

    CONSTRAINT fk_subscription_organization
        FOREIGN KEY (organization_id)
        REFERENCES security.organization (organization_id),

    CONSTRAINT fk_subscription_module
        FOREIGN KEY (subscription_module_id)
        REFERENCES security.subscription_module (subscription_module_id),

    CONSTRAINT fk_subscription_currency
        FOREIGN KEY (currency_lookup_data_id)
        REFERENCES public.lookup_data (lookup_data_id),

    CONSTRAINT ck_subscription_type
        CHECK (subscription_type IN ('Free Trial', 'Premium')),

    CONSTRAINT ck_subscription_billing_period
        CHECK (billing_period_type IN ('Monthly', 'Yearly')),

    CONSTRAINT ck_subscription_billing_count
        CHECK (billing_period_count > 0),

    CONSTRAINT ck_subscription_dates
        CHECK (subscription_end_date >= subscription_start_date),

    CONSTRAINT ck_subscription_exchange_rate
        CHECK (local_exchange_rate > 0),

    CONSTRAINT ck_subscription_amounts
        CHECK (
            subtotal_amount >= 0
            AND discount_percentage BETWEEN 0 AND 100
            AND discount_amount >= 0
            AND vat_amount >= 0
            AND total_amount >= 0
        ),

    -- The API calculates the discount and total; the database makes sure they add up.
    CONSTRAINT ck_subscription_total
        CHECK (
            discount_amount <= subtotal_amount
            AND total_amount = subtotal_amount - discount_amount + vat_amount
        ),

    CONSTRAINT ck_subscription_status
        CHECK (status IN ('Pending', 'Active', 'Expired', 'Cancelled'))
);

CREATE INDEX IF NOT EXISTS ix_subscription_organization
    ON security.subscription (organization_id);

CREATE INDEX IF NOT EXISTS ix_subscription_module
    ON security.subscription (subscription_module_id);

CREATE INDEX IF NOT EXISTS ix_subscription_currency
    ON security.subscription (currency_lookup_data_id);

CREATE INDEX IF NOT EXISTS ix_subscription_status_dates
    ON security.subscription
    (status, subscription_start_date, subscription_end_date);

CREATE INDEX IF NOT EXISTS ix_subscription_org_module_status
    ON security.subscription
    (organization_id, subscription_module_id, status);

-- =====================================================================
-- Permissions and menus
-- =====================================================================

INSERT INTO security."Permission" (code, name, description)
VALUES ('SETTING.V', 'View Settings', 'View lookup tables and lookup data'),
       ('SETTING.M', 'Manage Settings', 'Add, edit and delete lookup tables and lookup data')
ON CONFLICT (code) DO NOTHING;

INSERT INTO security."RolePermission" ("roleId", "permissionId")
SELECT r.id, p.id
FROM security."Role" r
JOIN security."Permission" p ON p.code IN ('SETTING.V', 'SETTING.M')
WHERE r.name = 'Super Admin'
ON CONFLICT DO NOTHING;

-- Security -> Subscription Modules, Subscriptions (after the existing children).
INSERT INTO security."Menu" (title, path, "sortOrder", "parentId", "isActive")
SELECT v.title,
       v.path,
       (SELECT coalesce(max(c."sortOrder"), 0) FROM security."Menu" c WHERE c."parentId" = parent.id) + v.position,
       parent.id,
       true
FROM security."Menu" parent
CROSS JOIN (VALUES ('Subscription Modules', '/security/subscription-modules', 1),
                   ('Subscriptions', '/security/subscriptions', 2)) AS v(title, path, position)
WHERE parent.title = 'Security' AND parent."parentId" IS NULL
  AND NOT EXISTS (SELECT 1 FROM security."Menu" m WHERE m.path = v.path);

-- Settings (new top-level group, last) -> Lookup Tables, Lookup Data.
INSERT INTO security."Menu" (title, path, "sortOrder", "isActive")
SELECT 'Settings', '#',
       (SELECT coalesce(max("sortOrder"), 0) + 1 FROM security."Menu" WHERE "parentId" IS NULL),
       true
WHERE NOT EXISTS (SELECT 1 FROM security."Menu" WHERE title = 'Settings' AND "parentId" IS NULL);

INSERT INTO security."Menu" (title, path, "sortOrder", "parentId", "isActive")
SELECT v.title, v.path, v.position, parent.id, true
FROM security."Menu" parent
CROSS JOIN (VALUES ('Lookup Tables', '/settings/lookup-tables', 1),
                   ('Lookup Data', '/settings/lookup-data', 2)) AS v(title, path, position)
WHERE parent.title = 'Settings' AND parent."parentId" IS NULL
  AND NOT EXISTS (SELECT 1 FROM security."Menu" m WHERE m.path = v.path);

COMMIT;
