-- SMS credit management for the shared ADN account.
-- Client identifiers are stored as text so this schema does not assume the
-- identifier type or table name used by the ERP's client/security schemas.

BEGIN;

CREATE SCHEMA IF NOT EXISTS sms;

CREATE TABLE IF NOT EXISTS sms.platform_wallet
(
    wallet_id        smallint PRIMARY KEY CHECK (wallet_id = 1),
    balance          bigint NOT NULL DEFAULT 0 CHECK (balance >= 0),
    total_purchased  bigint NOT NULL DEFAULT 0 CHECK (total_purchased >= 0),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

INSERT INTO sms.platform_wallet (wallet_id)
VALUES (1)
ON CONFLICT (wallet_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS sms.clients
(
    client_id    text PRIMARY KEY,
    display_name text NOT NULL,
    is_active    boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT clients_id_not_blank CHECK (length(btrim(client_id)) > 0),
    CONSTRAINT clients_name_not_blank CHECK (length(btrim(display_name)) > 0)
);

CREATE TABLE IF NOT EXISTS sms.client_wallets
(
    client_id       text PRIMARY KEY REFERENCES sms.clients(client_id),
    balance         bigint NOT NULL DEFAULT 0 CHECK (balance >= 0),
    total_allocated bigint NOT NULL DEFAULT 0 CHECK (total_allocated >= 0),
    total_consumed  bigint NOT NULL DEFAULT 0 CHECK (total_consumed >= 0),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sms.balance_transactions
(
    transaction_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type     text NOT NULL CHECK (transaction_type IN ('purchase', 'allocation', 'consumption')),
    quantity             bigint NOT NULL CHECK (quantity > 0),
    client_id            text REFERENCES sms.clients(client_id),
    platform_delta       bigint NOT NULL,
    client_delta         bigint NOT NULL,
    platform_balance_after bigint NOT NULL CHECK (platform_balance_after >= 0),
    client_balance_after bigint CHECK (client_balance_after >= 0),
    provider_reference   text UNIQUE,
    request_reference    text UNIQUE,
    note                 text,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT balance_transaction_shape CHECK
    (
        (transaction_type = 'purchase'
            AND client_id IS NULL AND platform_delta = quantity
            AND client_delta = 0 AND client_balance_after IS NULL)
        OR
        (transaction_type = 'allocation'
            AND client_id IS NOT NULL AND platform_delta = -quantity
            AND client_delta = quantity AND client_balance_after IS NOT NULL)
        OR
        (transaction_type = 'consumption'
            AND client_id IS NOT NULL AND platform_delta = 0
            AND client_delta = -quantity AND client_balance_after IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_sms_balance_transactions_client_created
    ON sms.balance_transactions (client_id, created_at DESC)
    WHERE client_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS sms.adn_purchases
(
    purchase_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id    bigint NOT NULL UNIQUE REFERENCES sms.balance_transactions(transaction_id),
    provider          text NOT NULL DEFAULT 'ADN',
    provider_reference text UNIQUE,
    sms_quantity      bigint NOT NULL CHECK (sms_quantity > 0),
    amount_paid       numeric(14, 2) CHECK (amount_paid IS NULL OR amount_paid >= 0),
    currency          char(3),
    purchased_at      timestamptz NOT NULL DEFAULT now(),
    note              text
);

CREATE TABLE IF NOT EXISTS sms.client_allocations
(
    allocation_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id bigint NOT NULL UNIQUE REFERENCES sms.balance_transactions(transaction_id),
    client_id      text NOT NULL REFERENCES sms.clients(client_id),
    sms_quantity   bigint NOT NULL CHECK (sms_quantity > 0),
    note           text,
    allocated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_sms_client_allocations_client_date
    ON sms.client_allocations (client_id, allocated_at DESC);

CREATE TABLE IF NOT EXISTS sms.usage_records
(
    usage_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id       bigint NOT NULL UNIQUE REFERENCES sms.balance_transactions(transaction_id),
    client_id            text NOT NULL REFERENCES sms.clients(client_id),
    request_reference    text NOT NULL UNIQUE,
    provider_message_id  text,
    recipient            text,
    sms_quantity         bigint NOT NULL CHECK (sms_quantity > 0),
    sent_at              timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_sms_usage_provider_message_id
    ON sms.usage_records (provider_message_id)
    WHERE provider_message_id IS NOT NULL;

CREATE OR REPLACE FUNCTION sms.record_adn_purchase
(
    p_sms_quantity bigint,
    p_provider_reference text DEFAULT NULL,
    p_amount_paid numeric DEFAULT NULL,
    p_currency char(3) DEFAULT NULL,
    p_purchased_at timestamptz DEFAULT now(),
    p_note text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, sms
AS $function$
DECLARE
    v_platform_balance bigint;
    v_transaction_id bigint;
BEGIN
    IF p_sms_quantity IS NULL OR p_sms_quantity <= 0 THEN
        RAISE EXCEPTION 'SMS quantity must be greater than zero';
    END IF;

    UPDATE sms.platform_wallet
       SET balance = balance + p_sms_quantity,
           total_purchased = total_purchased + p_sms_quantity,
           updated_at = now()
     WHERE wallet_id = 1
     RETURNING balance INTO v_platform_balance;

    INSERT INTO sms.balance_transactions
        (transaction_type, quantity, platform_delta, client_delta,
         platform_balance_after, provider_reference, note, created_at)
    VALUES
        ('purchase', p_sms_quantity, p_sms_quantity, 0,
         v_platform_balance, p_provider_reference, p_note, p_purchased_at)
    RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO sms.adn_purchases
        (transaction_id, provider_reference, sms_quantity, amount_paid,
         currency, purchased_at, note)
    VALUES
        (v_transaction_id, p_provider_reference, p_sms_quantity, p_amount_paid,
         p_currency, p_purchased_at, p_note);

    RETURN v_transaction_id;
END;
$function$;

CREATE OR REPLACE FUNCTION sms.allocate_sms
(
    p_client_id text,
    p_client_name text,
    p_sms_quantity bigint,
    p_note text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, sms
AS $function$
DECLARE
    v_platform_balance bigint;
    v_client_balance bigint;
    v_transaction_id bigint;
BEGIN
    IF p_client_id IS NULL OR length(btrim(p_client_id)) = 0 THEN
        RAISE EXCEPTION 'Client id must not be blank';
    END IF;
    IF p_client_name IS NULL OR length(btrim(p_client_name)) = 0 THEN
        RAISE EXCEPTION 'Client name must not be blank';
    END IF;
    IF p_sms_quantity IS NULL OR p_sms_quantity <= 0 THEN
        RAISE EXCEPTION 'SMS quantity must be greater than zero';
    END IF;

    -- Lock the shared pool first so concurrent allocations cannot overspend it.
    SELECT balance INTO v_platform_balance
      FROM sms.platform_wallet
     WHERE wallet_id = 1
     FOR UPDATE;

    IF v_platform_balance < p_sms_quantity THEN
        RAISE EXCEPTION 'Insufficient unallocated SMS balance: available %, requested %',
            v_platform_balance, p_sms_quantity;
    END IF;

    INSERT INTO sms.clients (client_id, display_name)
    VALUES (p_client_id, p_client_name)
    ON CONFLICT (client_id) DO UPDATE
        SET display_name = EXCLUDED.display_name,
            updated_at = now();

    INSERT INTO sms.client_wallets (client_id)
    VALUES (p_client_id)
    ON CONFLICT (client_id) DO NOTHING;

    SELECT balance INTO v_client_balance
      FROM sms.client_wallets
     WHERE client_id = p_client_id
     FOR UPDATE;

    UPDATE sms.platform_wallet
       SET balance = balance - p_sms_quantity,
           updated_at = now()
     WHERE wallet_id = 1
     RETURNING balance INTO v_platform_balance;

    UPDATE sms.client_wallets
       SET balance = balance + p_sms_quantity,
           total_allocated = total_allocated + p_sms_quantity,
           updated_at = now()
     WHERE client_id = p_client_id
     RETURNING balance INTO v_client_balance;

    INSERT INTO sms.balance_transactions
        (transaction_type, quantity, client_id, platform_delta, client_delta,
         platform_balance_after, client_balance_after, note)
    VALUES
        ('allocation', p_sms_quantity, p_client_id, -p_sms_quantity, p_sms_quantity,
         v_platform_balance, v_client_balance, p_note)
    RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO sms.client_allocations (transaction_id, client_id, sms_quantity, note)
    VALUES (v_transaction_id, p_client_id, p_sms_quantity, p_note);

    RETURN v_transaction_id;
END;
$function$;

CREATE OR REPLACE FUNCTION sms.consume_sms
(
    p_client_id text,
    p_sms_quantity bigint,
    p_request_reference text,
    p_recipient text DEFAULT NULL,
    p_provider_message_id text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, sms
AS $function$
DECLARE
    v_client_balance bigint;
    v_platform_balance bigint;
    v_transaction_id bigint;
    v_existing_client_id text;
    v_existing_quantity bigint;
    v_is_active boolean;
BEGIN
    IF p_sms_quantity IS NULL OR p_sms_quantity <= 0 THEN
        RAISE EXCEPTION 'SMS quantity must be greater than zero';
    END IF;
    IF p_request_reference IS NULL OR length(btrim(p_request_reference)) = 0 THEN
        RAISE EXCEPTION 'Request reference is required for idempotent SMS charging';
    END IF;

    SELECT is_active INTO v_is_active
      FROM sms.clients
     WHERE client_id = p_client_id;
    IF NOT FOUND OR NOT v_is_active THEN
        RAISE EXCEPTION 'SMS client is missing or inactive';
    END IF;

    -- Serialize charges for this client, including retries with the same reference.
    SELECT balance INTO v_client_balance
      FROM sms.client_wallets
     WHERE client_id = p_client_id
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'SMS wallet is not configured for client %', p_client_id;
    END IF;

    SELECT transaction_id, client_id, quantity
      INTO v_transaction_id, v_existing_client_id, v_existing_quantity
      FROM sms.balance_transactions
     WHERE request_reference = p_request_reference;
    IF FOUND THEN
        IF v_existing_client_id <> p_client_id OR v_existing_quantity <> p_sms_quantity THEN
            RAISE EXCEPTION 'Request reference has already been used for a different SMS charge';
        END IF;
        RETURN v_transaction_id;
    END IF;

    IF v_client_balance < p_sms_quantity THEN
        RAISE EXCEPTION 'Insufficient client SMS balance: available %, requested %',
            v_client_balance, p_sms_quantity;
    END IF;

    SELECT balance INTO v_platform_balance FROM sms.platform_wallet WHERE wallet_id = 1;

    UPDATE sms.client_wallets
       SET balance = balance - p_sms_quantity,
           total_consumed = total_consumed + p_sms_quantity,
           updated_at = now()
     WHERE client_id = p_client_id
     RETURNING balance INTO v_client_balance;

    INSERT INTO sms.balance_transactions
        (transaction_type, quantity, client_id, platform_delta, client_delta,
         platform_balance_after, client_balance_after, request_reference)
    VALUES
        ('consumption', p_sms_quantity, p_client_id, 0, -p_sms_quantity,
         v_platform_balance, v_client_balance, p_request_reference)
    RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO sms.usage_records
        (transaction_id, client_id, request_reference, provider_message_id,
         recipient, sms_quantity)
    VALUES
        (v_transaction_id, p_client_id, p_request_reference, p_provider_message_id,
         p_recipient, p_sms_quantity);

    RETURN v_transaction_id;
END;
$function$;

CREATE OR REPLACE FUNCTION sms.register_client
(
    p_client_id text,
    p_display_name text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, sms
AS $function$
BEGIN
    IF p_client_id IS NULL OR length(btrim(p_client_id)) = 0 THEN
        RAISE EXCEPTION 'Client id must not be blank';
    END IF;
    IF p_display_name IS NULL OR length(btrim(p_display_name)) = 0 THEN
        RAISE EXCEPTION 'Client name must not be blank';
    END IF;

    INSERT INTO sms.clients (client_id, display_name)
    VALUES (p_client_id, p_display_name);

    INSERT INTO sms.client_wallets (client_id)
    VALUES (p_client_id);
END;
$function$;

CREATE OR REPLACE FUNCTION sms.update_client
(
    p_client_id text,
    p_display_name text DEFAULT NULL,
    p_is_active boolean DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, sms
AS $function$
DECLARE
    v_rows_updated bigint;
BEGIN
    IF p_display_name IS NULL AND p_is_active IS NULL THEN
        RAISE EXCEPTION 'Provide a display name or active status to update';
    END IF;

    UPDATE sms.clients
       SET display_name = COALESCE(p_display_name, display_name),
           is_active = COALESCE(p_is_active, is_active),
           updated_at = now()
     WHERE client_id = p_client_id;

    GET DIAGNOSTICS v_rows_updated = ROW_COUNT;
    RETURN v_rows_updated > 0;
END;
$function$;

CREATE OR REPLACE VIEW sms.client_balance_summary AS
SELECT c.client_id,
       c.display_name,
       c.is_active,
       COALESCE(w.balance, 0) AS available_sms,
       COALESCE(w.total_allocated, 0) AS total_allocated_sms,
       COALESCE(w.total_consumed, 0) AS total_consumed_sms,
       c.created_at,
       c.updated_at
  FROM sms.clients c
  LEFT JOIN sms.client_wallets w USING (client_id);

CREATE OR REPLACE VIEW sms.platform_balance_summary AS
SELECT p.total_purchased AS total_purchased_sms,
       p.balance AS unallocated_sms,
       COALESCE(SUM(w.balance), 0) AS assigned_available_sms,
       COALESCE(SUM(w.total_consumed), 0) AS consumed_sms,
       p.balance + COALESCE(SUM(w.balance), 0) AS total_available_sms,
       p.updated_at
  FROM sms.platform_wallet p
  LEFT JOIN sms.client_wallets w ON true
 WHERE p.wallet_id = 1
 GROUP BY p.wallet_id, p.total_purchased, p.balance, p.updated_at;

COMMIT;
