INSERT INTO public.category (organization_id, parent_category_id, category_name, sort_order, is_active)
SELECT o.organization_id, pc.category_id, c.name, c.position, TRUE
FROM org o
CROSS JOIN children c
JOIN public.category pc
  ON pc.organization_id = o.organization_id AND pc.parent_category_id IS NULL AND lower(pc.category_name) = lower(c.parent)
ON CONFLICT (organization_id, parent_category_id, lower(category_name)) DO NOTHING;

-- What Farhad Computer has now.
SELECT p.sort_order, p.category_name AS parent, count(c.category_id) AS children
FROM public.category p
JOIN public.organization o ON o.organization_id = p.organization_id AND o.organization_slug = 'farhadcomputer'
LEFT JOIN public.category c ON c.parent_category_id = p.category_id
WHERE p.parent_category_id IS NULL
GROUP BY p.category_id, p.sort_order, p.category_name
ORDER BY p.sort_order, p.category_name;

