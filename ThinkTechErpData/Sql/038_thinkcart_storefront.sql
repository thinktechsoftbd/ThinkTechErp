CREATE INDEX IF NOT EXISTS supplier_address_supplier_id_idx ON public.supplier_address (supplier_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_supplier_address_one_default ON public.supplier_address (supplier_id) WHERE is_default;

CREATE TABLE IF NOT EXISTS public.otp_code
(
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id    UUID NOT NULL DEFAULT gen_random_uuid(),
    phone        TEXT NOT NULL,
    purpose      TEXT NOT NULL CHECK (purpose IN ('login', 'register', 'reset_password', 'order_verify')),
    code_hash    TEXT NOT NULL,                         -- never the plain code
    attempts     SMALLINT NOT NULL DEFAULT 0,
