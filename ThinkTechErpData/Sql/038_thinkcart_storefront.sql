-- Web settings of ONE sellable ERP product (one size). Code, price, cost and stock come from product and
-- stock_balance.
CREATE TABLE IF NOT EXISTS public.product_variant
(
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    product_id        INTEGER NOT NULL UNIQUE REFERENCES public.product (product_id),  -- the sellable size
    title             TEXT NOT NULL DEFAULT 'Default',    -- "500g", "1kg", "5 liter", "15g x 24 pcs"
    pack_size         NUMERIC(10, 3),
    pack_unit         TEXT CHECK (pack_unit IN ('g', 'kg', 'ml', 'l', 'pcs', 'box')),
    weight_g          INTEGER NOT NULL DEFAULT 0 CHECK (weight_g >= 0),  -- shipping weight incl. packaging
    compare_at_price  NUMERIC(12, 2) CHECK (compare_at_price IS NULL OR compare_at_price >= 0),  -- NULL = product.mrp
    min_order_qty     INTEGER NOT NULL DEFAULT 1 CHECK (min_order_qty > 0),
    max_order_qty     INTEGER,
    allow_backorder   BOOLEAN NOT NULL DEFAULT FALSE,
    is_default        BOOLEAN NOT NULL DEFAULT FALSE,     -- size pre-selected on the product page
    status            TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    sort_order        INTEGER NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

