-- Used on listing products: a product with no parent, or the parent of its sizes.
ALTER TABLE public.product
    ADD COLUMN IF NOT EXISTS object_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN IF NOT EXISTS listing_type      VARCHAR(20) NULL,    -- simple | variable | bundle; NULL = not a web listing
    ADD COLUMN IF NOT EXISTS slug              VARCHAR(260) NULL,
    ADD COLUMN IF NOT EXISTS short_description VARCHAR(1000) NULL,
    ADD COLUMN IF NOT EXISTS description       TEXT NULL,           -- rich text / HTML
    ADD COLUMN IF NOT EXISTS video_url         VARCHAR(500) NULL,
    ADD COLUMN IF NOT EXISTS web_status        VARCHAR(20) NULL,    -- draft | active | archived; NULL = not on the website
    ADD COLUMN IF NOT EXISTS is_featured       BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS sort_order        INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS meta_title        VARCHAR(200) NULL,
    ADD COLUMN IF NOT EXISTS meta_description  VARCHAR(500) NULL,
    ADD COLUMN IF NOT EXISTS published_at      TIMESTAMP(3) NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'ck_product_listing_type' AND conrelid = 'public.product'::regclass) THEN
        ALTER TABLE public.product
            ADD CONSTRAINT ck_product_listing_type
                CHECK (listing_type IS NULL OR listing_type IN ('simple', 'variable', 'bundle'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'ck_product_web_status' AND conrelid = 'public.product'::regclass) THEN
        ALTER TABLE public.product
            ADD CONSTRAINT ck_product_web_status
                CHECK (web_status IS NULL OR web_status IN ('draft', 'active', 'archived'));
