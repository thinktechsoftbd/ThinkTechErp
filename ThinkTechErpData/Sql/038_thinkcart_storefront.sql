ALTER TABLE public.supplier
    ADD COLUMN IF NOT EXISTS object_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN IF NOT EXISTS password_hash      VARCHAR(255) NULL,   -- NULL = guest (ordered without an account)
    ADD COLUMN IF NOT EXISTS gender             VARCHAR(10) NULL,
    ADD COLUMN IF NOT EXISTS date_of_birth      DATE NULL,
    ADD COLUMN IF NOT EXISTS mobile_verified_at TIMESTAMP(3) NULL,
