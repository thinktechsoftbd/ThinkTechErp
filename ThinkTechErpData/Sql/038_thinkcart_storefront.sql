-- "Related Products", "Frequently bought together", upsells.
CREATE TABLE IF NOT EXISTS public.product_relation
(
    product_id          INTEGER NOT NULL REFERENCES public.product (product_id) ON DELETE CASCADE,
    related_product_id  INTEGER NOT NULL REFERENCES public.product (product_id) ON DELETE CASCADE,
    relation_type       TEXT NOT NULL
                          CHECK (relation_type IN ('related', 'frequently_bought_together', 'upsell', 'cross_sell')),
    object_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    sort_order          INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, related_product_id, relation_type),
    CHECK (product_id <> related_product_id)
);

-- Combo packs: selling the bundle deducts stock from its components.
CREATE TABLE IF NOT EXISTS public.bundle_item
(
    bundle_variant_id     BIGINT NOT NULL REFERENCES public.product_variant (id) ON DELETE CASCADE,
    component_variant_id  BIGINT NOT NULL REFERENCES public.product_variant (id),
    object_id             UUID NOT NULL DEFAULT gen_random_uuid(),
    quantity              INTEGER NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (bundle_variant_id, component_variant_id),
    CHECK (bundle_variant_id <> component_variant_id)
);

