    consumed_at  TIMESTAMPTZ,
    request_ip   INET,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS otp_code_phone_purpose_created_at_idx ON public.otp_code (phone, purpose, created_at DESC);

-- Storefront customers' refresh tokens (api/thinkcart/auth). Only SHA-256 hashes are stored; revoked tokens
-- stay until they expire so a stolen, already rotated token is recognized if it comes back.
CREATE TABLE IF NOT EXISTS public.ecom_customer_token
(
    id                      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id               UUID NOT NULL DEFAULT gen_random_uuid(),
    customer_id             INTEGER NOT NULL REFERENCES public.supplier (supplier_id) ON DELETE CASCADE,
    token_hash              VARCHAR(64) NOT NULL,
    expires_at              TIMESTAMPTZ NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_ip           VARCHAR(45),
    revoked_at              TIMESTAMPTZ,
    replaced_by_token_hash  VARCHAR(64)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ecom_customer_token_hash ON public.ecom_customer_token (token_hash);
CREATE INDEX IF NOT EXISTS ix_ecom_customer_token_customer ON public.ecom_customer_token (customer_id);

