-- ThinkCart storefront: the e-commerce side of thinkcart/database/schema.sql (draft v0.2) for the api/thinkcart
-- area. Run after 035_settings_divisions_districts_shipping_zones.sql (it doesn't depend on the 036/037
-- warranty scripts); the script is idempotent.
--
--   * The seven ERP tables it extends (supplier, brand, category, product, warehouse, stock_balance,
--     stock_movement) get their e-commerce columns (ADD COLUMN IF NOT EXISTS), and object_id where they have
--     none. Existing columns, constraints and rows are left as they are.
--   * Every e-commerce table of schema.sql is created when missing (CREATE TABLE IF NOT EXISTS), with its
--     indexes (named as PostgreSQL names schema.sql's unnamed ones, so tables created from schema.sql match).
--     Staff columns reference public."User"(id).
--   * public.ecom_customer_token: storefront customers' rotating refresh tokens (SHA-256 hashes only).
--   * Reference rows (ON CONFLICT DO NOTHING): shipping zones, payment methods, couriers, and the store,
--     checkout and shipping settings.
--
-- Left out of schema.sql on purpose:
--   * purchase_order / purchase_order_item: the ERP has its own purchase documents (public.purchase_order is
--     the ERP's). stock_balance.purchase_order_item_id is added without a foreign key.
--   * ux_supplier_customer_mobile / ux_supplier_customer_email: existing ERP customers may share a mobile or
--     email, and the ERP's customer screens allow it. The API picks one (an account first, then the oldest);
--     new web customers stay unique through supplier_code 'WEB-' || mobile (ux_supplier_code).
--   * Dropping supplier's address columns: the ERP still reads them. supplier_address holds web addresses.
--   * updated_at triggers on the seven ERP tables: the ERP sets updated_at itself.
--   * pg_trgm and the trigram product-name index are created only where the extension is available.
--
-- Shipping rates (shipping_rate) are not seeded: enter each zone's weight bands and fees before checkout
-- (thinkcart/database/seed_reference.sql has placeholder bands). Payment methods other than cash on delivery
-- are added inactive, since v1 has no payment gateway.

BEGIN;

-- =====================================================================
-- updated_at helpers (created only when missing)
-- =====================================================================

DO $do$
BEGIN
    IF to_regprocedure('public.set_updated_at()') IS NULL THEN
        CREATE FUNCTION public.set_updated_at() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        BEGIN
            NEW.updated_at := now();
            RETURN NEW;
        END $fn$;
    END IF;

    IF to_regprocedure('public.set_updated_at_utc()') IS NULL THEN
        CREATE FUNCTION public.set_updated_at_utc() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        BEGIN
            NEW.updated_at := now() AT TIME ZONE 'utc';
            RETURN NEW;
        END $fn$;
    END IF;
END $do$;

-- =====================================================================
-- 1. Locations and shipping zones
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.shipping_zone
(
    id                 SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id          UUID NOT NULL DEFAULT gen_random_uuid(),
    code               TEXT NOT NULL UNIQUE,              -- inside_dhaka, dhaka_suburb, outside_dhaka
    name               TEXT NOT NULL,
    min_delivery_days  SMALLINT,
    max_delivery_days  SMALLINT,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Weight bands per zone. The fee is what the customer pays (the courier's charge is on shipment).
CREATE TABLE IF NOT EXISTS public.shipping_rate
(
    id                       INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id                UUID NOT NULL DEFAULT gen_random_uuid(),
    shipping_zone_id         SMALLINT NOT NULL REFERENCES public.shipping_zone (id),
    min_weight_g             INTEGER NOT NULL DEFAULT 0 CHECK (min_weight_g >= 0),
    max_weight_g             INTEGER,                     -- NULL = no upper bound
    fee                      NUMERIC(12, 2) NOT NULL CHECK (fee >= 0),
    free_shipping_min_order  NUMERIC(12, 2),              -- subtotal at/above which this band is free
    is_active                BOOLEAN NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (max_weight_g IS NULL OR max_weight_g > min_weight_g)
);
CREATE INDEX IF NOT EXISTS shipping_rate_shipping_zone_id_idx ON public.shipping_rate (shipping_zone_id);

CREATE TABLE IF NOT EXISTS public.division
(
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id   UUID NOT NULL DEFAULT gen_random_uuid(),
    name        TEXT NOT NULL UNIQUE,
    name_bn     TEXT,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by  INTEGER REFERENCES public."User" (id),
    updated_at  TIMESTAMP(3),
    updated_by  INTEGER REFERENCES public."User" (id)
);

CREATE TABLE IF NOT EXISTS public.district
(
    id                SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    division_id       SMALLINT NOT NULL REFERENCES public.division (id),
    name              TEXT NOT NULL,
    name_bn           TEXT,
    shipping_zone_id  SMALLINT REFERENCES public.shipping_zone (id),  -- NULL = the default zone in site_setting
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by        INTEGER REFERENCES public."User" (id),
    updated_at        TIMESTAMP(3),
    updated_by        INTEGER REFERENCES public."User" (id),
    UNIQUE (division_id, name)
);

CREATE TABLE IF NOT EXISTS public.area
(
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id         UUID NOT NULL DEFAULT gen_random_uuid(),
    district_id       SMALLINT NOT NULL REFERENCES public.district (id),
    name              TEXT NOT NULL,
    name_bn           TEXT,
    area_type         TEXT NOT NULL DEFAULT 'upazila' CHECK (area_type IN ('upazila', 'thana', 'city_area')),
    shipping_zone_id  SMALLINT REFERENCES public.shipping_zone (id),  -- overrides the district's zone
    courier_codes     JSONB NOT NULL DEFAULT '{}',
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    created_by        INTEGER REFERENCES public."User" (id),
    updated_at        TIMESTAMP(3),
    updated_by        INTEGER REFERENCES public."User" (id),
    UNIQUE (district_id, name)
);

