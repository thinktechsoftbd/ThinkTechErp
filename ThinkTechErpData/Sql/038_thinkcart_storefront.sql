-- Every SMS / email / WhatsApp sent (OTP, order confirmation, shipped, delivered).
CREATE TABLE IF NOT EXISTS public.message_log
(
    id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id            UUID NOT NULL DEFAULT gen_random_uuid(),
    channel              TEXT NOT NULL CHECK (channel IN ('sms', 'email', 'whatsapp', 'push')),
    recipient            TEXT NOT NULL,
    template_code        TEXT,                          -- otp, order_placed, order_shipped, order_delivered
    body                 TEXT,
    provider             TEXT,
    provider_message_id  TEXT,
    status               TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sent', 'delivered', 'failed')),
    cost                 NUMERIC(10, 4),
    error                TEXT,
    customer_id          INTEGER REFERENCES public.supplier (supplier_id) ON DELETE SET NULL,
    order_id             BIGINT REFERENCES public.ecom_order (id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at              TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS message_log_order_id_idx ON public.message_log (order_id);
CREATE INDEX IF NOT EXISTS message_log_created_at_idx ON public.message_log USING brin (created_at);

-- Who changed what in the admin panel (prices, stock, order edits).
CREATE TABLE IF NOT EXISTS public.audit_log
(
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    object_id    UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id      INTEGER REFERENCES public."User" (id),
    action       TEXT NOT NULL,                         -- create, update, delete, login, export
    entity_type  TEXT NOT NULL,                         -- product, ecom_order, coupon, ...
    entity_id    BIGINT,
    old_values   JSONB,
    new_values   JSONB,
    ip_address   INET,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_entity_type_entity_id_idx ON public.audit_log (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS audit_log_created_at_idx ON public.audit_log USING brin (created_at);

-- =====================================================================
-- 12. object_id indexes and updated_at triggers of the e-commerce tables
--     (the seven ERP tables got their object_id index above and keep no trigger)
-- =====================================================================

DO $$
DECLARE
    t       text;
    ts_type text;
    tables  text[] := ARRAY[
        'shipping_zone', 'shipping_rate', 'division', 'district', 'area',
        'supplier_address', 'otp_code', 'ecom_customer_token',
        'product_category', 'product_variant', 'product_image',
        'tag', 'product_tag', 'collection', 'collection_product', 'product_relation', 'bundle_item',
        'campaign', 'campaign_item', 'coupon', 'coupon_product', 'coupon_category',
        'visitor_session', 'cart', 'cart_item', 'wishlist_item',
        'payment_method', 'ecom_order', 'ecom_order_item', 'ecom_order_status_history',
        'courier', 'courier_payout', 'shipment', 'shipment_event',
        'payment', 'ecom_return', 'ecom_return_item', 'refund',
        'product_review', 'review_image', 'banner', 'ecom_testimonial', 'ecom_page', 'site_setting',
        'analytics_event', 'message_log', 'audit_log'];
BEGIN
    FOREACH t IN ARRAY tables LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = t AND column_name = 'object_id') THEN
            EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS %I ON public.%I (object_id)', 'ux_' || t || '_object_id', t);
        END IF;

        SELECT c.data_type INTO ts_type
        FROM information_schema.columns c
        WHERE c.table_schema = 'public' AND c.table_name = t AND c.column_name = 'updated_at';

        IF ts_type IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM pg_trigger
            WHERE tgrelid = format('public.%I', t)::regclass AND tgname = 'trg_' || t || '_updated_at') THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.%I()',
                           'trg_' || t || '_updated_at', t,
                           CASE WHEN ts_type = 'timestamp with time zone' THEN 'set_updated_at' ELSE 'set_updated_at_utc' END);
        END IF;
    END LOOP;
END $$;

