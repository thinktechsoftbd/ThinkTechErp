    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'ck_supplier_gender' AND conrelid = 'public.supplier'::regclass) THEN
        ALTER TABLE public.supplier
            ADD CONSTRAINT ck_supplier_gender CHECK (gender IS NULL OR gender IN ('male', 'female', 'other'));
    END IF;
END $$;

