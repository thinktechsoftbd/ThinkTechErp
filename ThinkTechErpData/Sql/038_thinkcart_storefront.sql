CREATE INDEX IF NOT EXISTS ix_product_web_status ON public.product (web_status) WHERE web_status IS NOT NULL;

-- Fuzzy product search, where the server has pg_trgm.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_trgm') THEN
        BEGIN
            CREATE EXTENSION IF NOT EXISTS pg_trgm;
            EXECUTE 'CREATE INDEX IF NOT EXISTS ix_product_name_trgm ON public.product USING gin (product_name gin_trgm_ops)';
        EXCEPTION WHEN insufficient_privilege THEN
            RAISE NOTICE 'pg_trgm not installed (insufficient privilege): ix_product_name_trgm skipped.';
        END;
    ELSE
        RAISE NOTICE 'pg_trgm is not available on this server: ix_product_name_trgm skipped.';
    END IF;
END $$;

-- Extra browse categories (Honey + Organic). product.category_id stays the reporting one.
