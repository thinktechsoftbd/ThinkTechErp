-- Subscription plans with their features (header) and each feature's details (lines), and the
-- Security -> Subscription Plan menu.
--   * subscription_plan: the plan, its price in a currency of the Currency lookup table, and its billing period.
--     plan_discount_price is the price after plan_discount_pct.
--   * subscription_plan_feature_h: the plan's features (a title each); deleting a plan deletes them.
--   * subscription_plan_feature_d: the lines under a feature; deleting a feature deletes them.
-- The screen reads with SECURITY.V and saves with SECURITY.M (the API's security policies).
-- Run after 027_security_organization_client_acting_user_optional.sql. The script is idempotent.

BEGIN;

CREATE TABLE IF NOT EXISTS public.subscription_plan
(
    id                          INT4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id                   UUID NOT NULL DEFAULT gen_random_uuid(),
    subscription_plan_name_en   VARCHAR(150) NOT NULL,
    subscription_plan_name_loc  VARCHAR(150) NULL,
    plan_short_note             VARCHAR(500) NULL,
    plan_regular_price          NUMERIC(18, 2) NOT NULL DEFAULT 0,
    plan_discount_pct           NUMERIC(5, 2) NOT NULL DEFAULT 0,
    plan_discount_price         NUMERIC(18, 2) NOT NULL DEFAULT 0,
    rf_currency_id              INT8 NOT NULL,   -- lookup "Currency"
    loc_exchange_rate           NUMERIC(18, 6) NOT NULL DEFAULT 1,
    billing_period_type         VARCHAR(20) NOT NULL,
    is_active                   BOOL NOT NULL DEFAULT TRUE,
    created_at                  TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
    created_by                  INT4 NULL,
    updated_at                  TIMESTAMP(3) NULL,
    updated_by                  INT4 NULL,

    CONSTRAINT fk_subscription_plan_currency
        FOREIGN KEY (rf_currency_id) REFERENCES public.lookup_data (lookup_data_id),
    CONSTRAINT fk_subscription_plan_created_by
        FOREIGN KEY (created_by) REFERENCES public."User" (id),
    CONSTRAINT fk_subscription_plan_updated_by
        FOREIGN KEY (updated_by) REFERENCES public."User" (id),
    CONSTRAINT ck_subscription_plan_price
        CHECK (plan_regular_price >= 0 AND plan_discount_price >= 0 AND plan_discount_price <= plan_regular_price),
    CONSTRAINT ck_subscription_plan_discount_pct
        CHECK (plan_discount_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_subscription_plan_exchange_rate
        CHECK (loc_exchange_rate > 0),
    CONSTRAINT ck_subscription_plan_billing_period
        CHECK (billing_period_type IN ('Monthly', 'Yearly'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_plan_object_id ON public.subscription_plan (object_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_plan_name ON public.subscription_plan (lower(subscription_plan_name_en));

CREATE TABLE IF NOT EXISTS public.subscription_plan_feature_h
(
    id                      INT4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id               UUID NOT NULL DEFAULT gen_random_uuid(),
    subscription_plan_id    INT4 NOT NULL,
    feature_title           VARCHAR(200) NOT NULL,
    is_active               BOOL NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
    created_by              INT4 NULL,
    updated_at              TIMESTAMP(3) NULL,
    updated_by              INT4 NULL,

    CONSTRAINT fk_subscription_plan_feature_h_plan
        FOREIGN KEY (subscription_plan_id) REFERENCES public.subscription_plan (id) ON DELETE CASCADE,
    CONSTRAINT fk_subscription_plan_feature_h_created_by
        FOREIGN KEY (created_by) REFERENCES public."User" (id),
    CONSTRAINT fk_subscription_plan_feature_h_updated_by
        FOREIGN KEY (updated_by) REFERENCES public."User" (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_plan_feature_h_object_id ON public.subscription_plan_feature_h (object_id);
CREATE INDEX IF NOT EXISTS ix_subscription_plan_feature_h_plan ON public.subscription_plan_feature_h (subscription_plan_id);

CREATE TABLE IF NOT EXISTS public.subscription_plan_feature_d
(
    id                              INT4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id                       UUID NOT NULL DEFAULT gen_random_uuid(),
    subscription_plan_feature_h_id  INT4 NOT NULL,
    feature_description             VARCHAR(500) NOT NULL,

    CONSTRAINT fk_subscription_plan_feature_d_header
        FOREIGN KEY (subscription_plan_feature_h_id) REFERENCES public.subscription_plan_feature_h (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_plan_feature_d_object_id ON public.subscription_plan_feature_d (object_id);
CREATE INDEX IF NOT EXISTS ix_subscription_plan_feature_d_header ON public.subscription_plan_feature_d (subscription_plan_feature_h_id);

COMMENT ON TABLE public.subscription_plan IS 'Subscription plans: price, discount, currency and billing period.';
COMMENT ON COLUMN public.subscription_plan.plan_discount_price IS 'The price after plan_discount_pct.';
COMMENT ON TABLE public.subscription_plan_feature_h IS 'The features of a subscription plan (header).';
COMMENT ON TABLE public.subscription_plan_feature_d IS 'The detail lines of a subscription plan feature.';

-- Security -> Subscription Plan, after the menus already there.
INSERT INTO public."Menu" (title, path, icon, "sortOrder", "parentId", "roleId", "isActive")
SELECT 'Subscription Plan',
       '/security/subscription-plans',
       'badge-dollar-sign',
       (SELECT coalesce(max(c."sortOrder"), 0) + 1 FROM public."Menu" c WHERE c."parentId" = parent.id),
       parent.id,
       NULL,
       true
FROM public."Menu" parent
WHERE parent.title = 'Security' AND parent."parentId" IS NULL
  AND NOT EXISTS (SELECT 1 FROM public."Menu" m WHERE m.path = '/security/subscription-plans');

COMMIT;
