-- Stores the integration clients previously configured under Authentication:Clients.
-- Run after 023_payment_sources.sql; the API and this migration use the shared public schema.
-- The script is idempotent and adds the two existing API clients as initial rows.

BEGIN;

CREATE TABLE IF NOT EXISTS public.security_organization_client
(
    id                  INT4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id           UUID NOT NULL DEFAULT gen_random_uuid(),
    client_name         TEXT NOT NULL,
    client_secret       TEXT NOT NULL,
    org_object_id       UUID NOT NULL,
    secret_sha256_hash  CHAR(64) NOT NULL,
    acting_user_id      INT4 NULL,
    scopes              TEXT[] NOT NULL,
    is_active           BOOL NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
    created_by          INT4 NULL,
    updated_at          TIMESTAMP(3) NULL,
    updated_by          INT4 NULL,

    CONSTRAINT fk_security_organization_client_organization
        FOREIGN KEY (org_object_id) REFERENCES public.organization (object_id),
    CONSTRAINT fk_security_organization_client_created_by
        FOREIGN KEY (created_by) REFERENCES public."User" (id),
    CONSTRAINT fk_security_organization_client_updated_by
        FOREIGN KEY (updated_by) REFERENCES public."User" (id),
    CONSTRAINT ck_security_organization_client_name
        CHECK (client_name ~ '^[A-Za-z0-9][A-Za-z0-9_]{2,63}$'),
    CONSTRAINT ck_security_organization_client_hash
        CHECK (secret_sha256_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_security_organization_client_scopes
        CHECK (cardinality(scopes) BETWEEN 1 AND 50 AND array_position(scopes, NULL) IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_security_organization_client_object_id
    ON public.security_organization_client (object_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_security_organization_client_name
    ON public.security_organization_client (lower(client_name));

CREATE INDEX IF NOT EXISTS ix_security_organization_client_acting_user
    ON public.security_organization_client (acting_user_id);

CREATE INDEX IF NOT EXISTS ix_security_organization_client_org_object_id
    ON public.security_organization_client (org_object_id);

-- Security client APIs use the existing security view/manage authorization policies.
INSERT INTO public."Permission" (code, name, description)
VALUES ('SECURITY.V', 'View Security', 'View users, roles, permissions, menus, and API clients'),
       ('SECURITY.M', 'Manage Security', 'Manage users, roles, permissions, menus, and API clients')
ON CONFLICT (code) DO NOTHING;

INSERT INTO public."RolePermission" ("roleId", "permissionId")
SELECT r.id, p.id
FROM public."Role" r
JOIN public."Permission" p ON p.code IN ('SECURITY.V', 'SECURITY.M')
WHERE r.name = 'Super Admin'
ON CONFLICT DO NOTHING;

-- Security -> Clients, beside Subscription Modules and Subscriptions.
INSERT INTO public."Menu" (title, path, icon, "sortOrder", "parentId", "roleId", "isActive")
SELECT 'Clients',
       '/security/clients',
       'key-round',
       (SELECT coalesce(max(c."sortOrder"), 0) + 1 FROM public."Menu" c WHERE c."parentId" = parent.id),
       parent.id,
       NULL,
       true
FROM public."Menu" parent
WHERE parent.title = 'Security' AND parent."parentId" IS NULL
  AND NOT EXISTS (SELECT 1 FROM public."Menu" m WHERE m.path = '/security/clients');

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public."User" WHERE id = 1) THEN
        RAISE EXCEPTION 'The sample API clients require public."User" id 1. Create that user or update the client seed rows before running this migration.';
    END IF;
END;
$$;

